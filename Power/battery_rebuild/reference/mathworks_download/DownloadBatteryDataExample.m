%[text] # Download Battery Data
%[text] This example downloads hybrid pulse power characterization (HPPC) test data performed on a BAK N18650CL-29 18650 type lithium-ion cell \[[1](internal:M_0163)\]. This data is required to run multiple examples in Simscape™ Battery™.
%[text] A BioLogic© `BCS-815` eight-channel battery tester, equipped with standard cables, accessories, and thermocouples, performed the battery HPPC tests \[[2](internal:M_0163)\]. The test chamber maintained the temperature and humidity control. To measure the temperature, the tester used the Agilent© `34972A` data acquisition system equipped with multiplexer capabilities. The system tested three different samples. The test was reproducible each time. The cells were tested at five different uniform chamber temperatures: 0°C,10°C,25°C,35°C, and 45°*C*.
